import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

let sha = 'unknown';
let builtAt = new Date().toISOString();

try {
  sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf-8' }).trim();
} catch {
  // not a git repo or git not available
}

try {
  // Use git log timestamp for reproducibility
  const ts = execFileSync('git', ['log', '-1', '--format=%cI'], { encoding: 'utf-8' }).trim();
  if (ts) builtAt = ts;
} catch { /* keep Date.now() fallback */ }

const content = `// Auto-generated by scripts/gen-build-info.mjs — do not edit manually
export const BUILD_SHA = '${sha}';
export const BUILT_AT = '${builtAt}';
`;

writeFileSync('src/build-info.ts', content, 'utf-8');
console.log(`Build info written: SHA=${sha}, built=${builtAt}`);
